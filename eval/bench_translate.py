"""Translation benchmark: how many tokens `--translate` saves, language by language.

The same four technical paragraphs in ten languages (``eval/corpus/parallel.json``)
go through shrink's translate step (NLLB-200 600M int8 on CPU). For every
language: tokens of the text, of the English reference and after translation
(o200k_base, exact), the "tokenizer tax" (language / English), how many
paragraphs the safety rules accepted, chrF against the English reference, and
the time per paragraph.

    python eval/bench_translate.py

Needs `pip install -e ".[translate]"`, `shrink --download translate` and
`shrink --download tokenizer`. No network while it runs.
"""

from __future__ import annotations

import json
import sys
import time
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from corpus import CORPUS, ROOT, python_version

from shrink.compressors.translate import load_backend, translate_text
from shrink.observability.stats import TiktokenCounter

RESULTS = ROOT / "eval" / "results"
NAMES = {
    "en": "English",
    "uk": "Ukrainian",
    "ru": "Russian",
    "pl": "Polish",
    "de": "German",
    "es": "Spanish",
    "fr": "French",
    "zh": "Chinese",
    "ja": "Japanese",
    "ar": "Arabic",
}


def chrf(hypothesis: str, reference: str, max_n: int = 6, beta: float = 2.0) -> float:
    """chrF (Popović 2015): F-score over character n-grams, 0..100, spaces ignored."""
    hyp = "".join(hypothesis.split())
    ref = "".join(reference.split())
    precisions, recalls = [], []
    for n in range(1, max_n + 1):
        h = Counter(hyp[i : i + n] for i in range(len(hyp) - n + 1))
        r = Counter(ref[i : i + n] for i in range(len(ref) - n + 1))
        if not h or not r:
            continue
        overlap = sum((h & r).values())
        precisions.append(overlap / sum(h.values()))
        recalls.append(overlap / sum(r.values()))
    if not precisions:
        return 0.0
    p = sum(precisions) / len(precisions)
    r = sum(recalls) / len(recalls)
    if p == 0 and r == 0:
        return 0.0
    return 100 * (1 + beta**2) * p * r / (beta**2 * p + r)


def main() -> None:
    data = json.loads((CORPUS / "parallel.json").read_text(encoding="utf-8"))
    count = TiktokenCounter().count
    backend = load_backend()
    english = data["en"]
    english_tokens = sum(count(p) for p in english)
    rows = []
    for code, name in NAMES.items():
        paragraphs = data[code]
        before = sum(count(p) for p in paragraphs)
        started = time.perf_counter()
        outputs = [translate_text(p + "\n", backend, count).rstrip("\n") for p in paragraphs]
        seconds = time.perf_counter() - started
        after = sum(count(p) for p in outputs)
        accepted = sum(1 for src, out in zip(paragraphs, outputs, strict=True) if src != out)
        quality = sum(chrf(o, e) for o, e in zip(outputs, english, strict=True)) / len(english)
        rows.append(
            {
                "code": code,
                "language": name,
                "tokens": before,
                "tax": before / english_tokens,
                "after": after,
                "saved_percent": (before - after) / before * 100,
                "accepted": accepted,
                "paragraphs": len(paragraphs),
                "chrf": quality,
                "ms_per_paragraph": seconds / len(paragraphs) * 1000,
                "sample": outputs[0],
            }
        )
        print(f"{name:<10} {before:>4} -> {after:>4} tokens, {accepted}/{len(paragraphs)} kept")
    RESULTS.mkdir(parents=True, exist_ok=True)
    (RESULTS / "translate.json").write_text(
        json.dumps({"env": python_version(), "rows": rows}, ensure_ascii=False, indent=1) + "\n",
        encoding="utf-8",
        newline="\n",
    )
    lines = [
        "# Translation benchmark",
        "",
        f"{python_version()}; NLLB-200 distilled 600M int8 (CTranslate2, CPU), tokens o200k_base.",
        f"Four parallel paragraphs; English reference: {english_tokens} tokens.",
        "Generated by `python eval/bench_translate.py`.",
        "",
        "| Language | Tokens | vs English | After `--translate` | Saved | Paragraphs translated"
        " | chrF vs English | ms / paragraph |",
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for row in rows:
        lines.append(
            f"| {row['language']} | {row['tokens']} | {row['tax']:.2f}x | {row['after']} | "
            f"{row['saved_percent']:.1f}% | {row['accepted']}/{row['paragraphs']} | "
            f"{row['chrf']:.1f} | {row['ms_per_paragraph']:.0f} |"
        )
    lines += ["", "## First paragraph after translation", ""]
    lines += [f"- **{row['language']}**: {row['sample']}" for row in rows]
    report = "\n".join(lines) + "\n"
    (RESULTS / "translate.md").write_text(report, encoding="utf-8", newline="\n")
    print(report)


if __name__ == "__main__":
    main()
