"""Start-up time (NFR-1): how long shrink takes on a tiny input, against bare Python.

Each command runs ``--runs`` times (after warm-up runs); the table shows the
median and the 90th percentile. ``python -X importtime`` then lists the imports
that cost the most when the CLI loads.

    python eval/bench_startup.py [--runs 20]
"""

from __future__ import annotations

import argparse
import platform
import re
import shutil
import statistics
import subprocess
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from corpus import ROOT, python_version

RESULTS = ROOT / "eval" / "results"
PY = sys.executable


def command_set() -> list[tuple[str, list[str], bytes]]:
    launcher = shutil.which("shrink", path=str(Path(PY).parent)) or shutil.which("shrink")
    sample = b"hello   world\n\n\n"
    commands = [
        ("python -c pass", [PY, "-c", "pass"], b""),
        ("python -c 'import shrink.cli'", [PY, "-c", "import shrink.cli"], b""),
        ("python -m shrink -V", [PY, "-m", "shrink", "-V"], b""),
        ("echo text | python -m shrink", [PY, "-m", "shrink"], sample),
        ("echo text | python -m shrink --stats", [PY, "-m", "shrink", "--stats"], sample),
    ]
    if launcher:
        commands.insert(3, ("shrink -V (installed launcher)", [launcher, "-V"], b""))
        commands.append(("echo text | shrink (installed launcher)", [launcher], sample))
    return commands


def measure(argv: list[str], stdin: bytes, runs: int, warmup: int = 3) -> list[float]:
    times = []
    for i in range(warmup + runs):
        started = time.perf_counter()
        subprocess.run(argv, input=stdin, capture_output=True, check=True)
        if i >= warmup:
            times.append((time.perf_counter() - started) * 1000)
    return times


def top_imports(limit: int = 10) -> list[tuple[int, str]]:
    result = subprocess.run(
        [PY, "-X", "importtime", "-c", "import shrink.cli"],
        capture_output=True,
        text=True,
        check=True,
    )
    rows = []
    for line in result.stderr.splitlines():
        match = re.match(r"import time:\s+\d+ \|\s+(\d+) \|(\s*)(\S+)", line)
        if match and len(match.group(2)) <= 2:  # top-level imports only
            rows.append((int(match.group(1)), match.group(3)))
    return sorted(rows, reverse=True)[:limit]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--runs", type=int, default=20)
    args = parser.parse_args()
    rows = []
    for name, argv, stdin in command_set():
        times = measure(argv, stdin, args.runs)
        median = statistics.median(times)
        p90 = sorted(times)[int(len(times) * 0.9) - 1]
        rows.append((name, median, p90))
        print(f"{name:<42} median {median:7.1f} ms   p90 {p90:7.1f} ms")
    base = rows[0][1]
    lines = [
        "# Start-up time",
        "",
        f"{python_version()} on {platform.system()} {platform.release()}, "
        f"{args.runs} runs after 3 warm-up runs. Generated by `python eval/bench_startup.py`.",
        "",
        "| Command | Median, ms | p90, ms | Over `python -c pass`, ms |",
        "| --- | ---: | ---: | ---: |",
    ]
    lines += [f"| `{n}` | {m:.0f} | {p:.0f} | {m - base:+.0f} |" for n, m, p in rows]
    lines += ["", "## Costliest imports of `import shrink.cli` (cumulative, ms)", ""]
    lines += [f"- `{name}`: {us / 1000:.1f}" for us, name in top_imports()]
    report = "\n".join(lines) + "\n"
    RESULTS.mkdir(parents=True, exist_ok=True)
    (RESULTS / "startup.md").write_text(report, encoding="utf-8", newline="\n")
    print(report)


if __name__ == "__main__":
    main()
